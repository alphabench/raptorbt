#!/usr/bin/env python
"""Generate ``docs/api/*.md``: the API reference, from the installed package.

The reference has one source: each public module's ``__all__`` and the
docstrings and signatures of the objects it names. Nothing in ``docs/api`` is
written by hand, so code, docs and skills cannot disagree about a name.

    python scripts/gen_api_reference.py             # rewrite docs/api
    python scripts/gen_api_reference.py --check     # exit 1 when docs/api is stale
    python scripts/gen_api_reference.py --missing   # public names and members with no docstring
    python scripts/gen_api_reference.py --require-docstrings   # exit 1 when a public name has none

Run it against the build you are documenting (``maturin develop --release``);
the output follows what is installed, not what the source tree says.
"""

from __future__ import annotations

import argparse
import importlib
import inspect
import re
import sys
from pathlib import Path
from types import ModuleType
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "api"
BANNER = (
    "<!-- Generated by scripts/gen_api_reference.py from the installed package. "
    "Do not edit: change the docstring and regenerate. -->"
)
NO_DOC = "*No docstring.*"
_ADDRESS = re.compile(r" at 0x[0-9a-fA-F]+")


def public_surface() -> dict[str, list[str]]:
    """Public module -> its public names, the surface ``raptorbt.skills check`` covers."""
    from raptorbt.skills._check import public_surface as surface

    return {m: names for m, names in surface().items() if names}


def _doc(obj: Any) -> str:
    """The object's own docstring (never one inherited from a base), cleaned."""
    raw = getattr(obj, "__doc__", None)
    if not isinstance(raw, str) or isinstance(obj, (int, float, str, tuple, frozenset)):
        return ""
    return inspect.cleandoc(raw)


def _signature(obj: Any) -> str | None:
    try:
        return _ADDRESS.sub("", str(inspect.signature(obj)))
    except (TypeError, ValueError):
        return None


def _first_line(doc: str) -> str:
    return doc.split("\n\n", 1)[0].replace("\n", " ").strip() if doc else ""


def _kind(obj: Any) -> str:
    if isinstance(obj, ModuleType):
        return "module"
    if inspect.isclass(obj):
        return "exception" if issubclass(obj, BaseException) else "class"
    if callable(obj):
        return "function"
    return "constant"


def _members(cls: type) -> list[tuple[str, str, str, str]]:
    """Public members of a class: (name, kind, signature or '', docstring)."""
    seen: dict[str, tuple[str, str, str, str]] = {}
    for klass in reversed(cls.__mro__):
        if klass is not cls and klass.__module__ == "builtins":
            continue  # object, ValueError, ...: not ours
        for name, raw in vars(klass).items():
            if name.startswith("_"):
                continue
            attr = raw.__func__ if isinstance(raw, (staticmethod, classmethod)) else raw
            if isinstance(raw, property) or type(raw).__name__ in ("getset_descriptor", "member_descriptor"):
                kind, sig = "property", ""
            elif callable(attr):
                kind, sig = "method", _signature(attr) or "(...)"
            else:
                kind, sig = "attribute", ""
            seen[name] = (name, kind, sig, _doc(raw if kind == "property" else attr))
    return sorted(seen.values())


def _render_member_table(members: list[tuple[str, str, str, str]]) -> list[str]:
    out = ["", "| Member | What it is |", "| --- | --- |"]
    for name, kind, sig, doc in members:
        label = f"`{name}{sig}`" if kind == "method" else f"`{name}`"
        text = (_first_line(doc) or NO_DOC).replace("|", "\\|")
        out.append(f"| {label} | {text} |")
    return out


def render_name(module: ModuleType, name: str, missing: list[str]) -> list[str]:
    obj = getattr(module, name)
    kind = _kind(obj)
    qual = f"{module.__name__}.{name}"
    out = [f"### `{name}`", "", f"*{kind}*"]
    if kind in ("class", "exception"):
        bases = [b.__name__ for b in obj.__bases__ if b is not object]
        sig = _signature(obj)
        head = f"class {name}" + (f"({', '.join(bases)})" if bases else "")
        out += ["", "```python", head + (f"\n{name}{sig}" if sig else ""), "```"]
    elif kind == "function":
        out += ["", "```python", f"{name}{_signature(obj) or '(...)'}", "```"]
    elif kind == "constant":
        out += ["", "```python", f"{name} = {_ADDRESS.sub('', repr(obj))}", "```"]
    doc = _doc(obj) if kind != "constant" else ""
    if kind == "module":
        doc = doc or ""
        out += ["", f"See [`{obj.__name__}`]({obj.__name__}.md)."]
    if kind != "constant":
        out += ["", doc or NO_DOC]
        if not doc:
            missing.append(qual)
    if kind in ("class", "exception"):
        members = _members(obj)
        if members:
            out += _render_member_table(members)
            for member, _k, _s, mdoc in members:
                if not mdoc:
                    missing.append(f"{qual}.{member}")
    out.append("")
    return out


def render_module(modname: str, names: list[str], missing: list[str]) -> str:
    module = importlib.import_module(modname)
    lines = [BANNER, "", f"# `{modname}`", ""]
    mdoc = _doc(module)
    if mdoc:
        lines += [mdoc, ""]
    else:
        missing.append(modname)
    lines += ["| Name | Kind | Summary |", "| --- | --- | --- |"]
    for name in names:
        obj = getattr(module, name)
        kind = _kind(obj)
        summary = _first_line(_doc(obj)) if kind != "constant" else f"`{_ADDRESS.sub('', repr(obj))}`"
        lines.append(f"| [`{name}`](#{name.lower()}) | {kind} | {summary.replace('|', chr(92) + '|')} |")
    lines.append("")
    for name in sorted(names):
        lines += render_name(module, name, missing)
    return "\n".join(lines).rstrip("\n") + "\n"


def render_index(surface: dict[str, list[str]], missing: list[str]) -> str:
    lines = [
        BANNER,
        "",
        "# API reference",
        "",
        "One page per public module, generated from its `__all__`, its signatures and its docstrings.",
        "Concepts and worked examples are in the [skills](../../skills/INDEX.md); this is the lookup table.",
        "",
        "| Module | Public names |",
        "| --- | --- |",
    ]
    for modname, names in sorted(surface.items()):
        lines.append(f"| [`{modname}`]({modname}.md) | {len(names)} |")
    lines += ["", f"Public names and members still without a docstring: {len(missing)}.", ""]
    return "\n".join(lines)


def generate() -> tuple[dict[str, str], list[str]]:
    """Every generated file (path relative to ``docs/api``) and the names missing a docstring."""
    surface = public_surface()
    missing: list[str] = []
    files = {f"{m}.md": render_module(m, names, missing) for m, names in sorted(surface.items())}
    files["README.md"] = render_index(surface, missing)
    return files, sorted(set(missing))


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail when docs/api differs from what the package generates")
    ap.add_argument("--missing", action="store_true", help="list public names and members with no docstring")
    ap.add_argument(
        "--require-docstrings",
        action="store_true",
        help="exit 1 when a public name (not a member) has no docstring, and list them",
    )
    args = ap.parse_args(argv)

    files, missing = generate()
    names = {f"{m}.{n}" for m, ns in public_surface().items() for n in ns} | set(public_surface())
    if args.missing:
        print("\n".join(f"{'name' if q in names else 'member'} {q}" for q in missing))
        return 0
    if args.require_docstrings:
        bare = [q for q in missing if q in names]
        for q in bare:
            print(f"no docstring: {q}", file=sys.stderr)
        return 1 if bare else 0
    if args.check:
        stale = [n for n, text in files.items() if not (OUT / n).is_file() or (OUT / n).read_text() != text]
        stale += [p.name for p in OUT.glob("*.md") if p.name not in files] if OUT.is_dir() else []
        if stale:
            print(f"docs/api is stale: {', '.join(sorted(set(stale)))}; run python scripts/gen_api_reference.py", file=sys.stderr)
            return 1
        print(f"docs/api is current ({len(files)} files)")
        return 0
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("*.md"):
        if old.name not in files:
            old.unlink()
    for name, text in files.items():
        (OUT / name).write_text(text)
    print(f"wrote {len(files)} files to docs/api; {len(missing)} names without a docstring (--missing lists them)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
