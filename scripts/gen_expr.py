#!/usr/bin/env python
"""Generate ``skills/expressions/functions.md``: every expression function, from the registry.

Nothing in that page is written by hand. The source is the engine's function registry, read
through ``raptorbt.expressions``, so a function added to the registry appears here (and as a
``raptorbt.col`` method, and in ``capabilities()["functions"]``) with no other edit.

    python scripts/gen_expr.py            # rewrite the page
    python scripts/gen_expr.py --check    # exit 1 when the page is stale

Run it against the build you are documenting (``maturin develop --release``).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "skills" / "expressions" / "functions.md"
BANNER = (
    "<!-- Generated by scripts/gen_expr.py from the function registry. "
    "Do not edit: change the registry and regenerate. -->"
)


def _param(p: dict) -> str:
    r = p["range"]
    if p["kind"] == "enum":
        span = " | ".join(f'"{v}"' for v in r["values"])
    else:
        span = f"{p['kind']} in [{r['min']}, {r['max']}]"
    default = "required" if p["default"] is None else f"default {p['default']!r}"
    return f"`{p['name']}`: {span}, {default}"


def _legacy(row: dict) -> str | None:
    lg = row["legacy"]
    if lg is None:
        return None
    exact = "bitwise" if lg["tolerance"] == 0 else f"within {lg['tolerance']:g}"
    return (
        f"pinned to `{lg['pinned_to']}` ({exact} on finite input); "
        f"a NaN input is handled as `{lg['nan']}` by the legacy indicator"
    )


def render(rows: list[dict]) -> str:
    families: dict[str, list[dict]] = {}
    for row in rows:
        families.setdefault(row["family"], []).append(row)
    out = [
        BANNER,
        "",
        "# Expression functions",
        "",
        f"{len(rows)} function{'s' * (len(rows) != 1)} in {len(families)} "
        f"{'family' if len(families) == 1 else 'families'}, sorted by family and name. "
        "Call them in text (`sma(close, 20)`) or as `raptorbt.col` methods "
        "(`raptorbt.col.close.sma(20)`). An input left out reads its default field.",
    ]
    for family in sorted(families):
        out += ["", f"## {family}"]
        for row in sorted(families[family], key=lambda r: r["name"]):
            out += ["", f"### `{row['signature']}`", "", row["doc"], ""]
            inputs = ", ".join(
                f"`{i['name']}`"
                + (" (boolean)" if i.get("elem") == "bool" else "")
                + (f" (default `{i['default_field']}`)" if i["default_field"] else "")
                for i in row["inputs"]
            )
            out.append(f"- inputs: {inputs}")
            out.append("- parameters: " + ("; ".join(_param(p) for p in row["params"]) or "none"))
            kind = "boolean" if row["out_kind"] == "bool" else "numeric"
            out.append(f"- outputs: {', '.join(f'`{o}`' for o in row['outputs'])} ({kind})")
            warm = row["warmup_at_defaults"]
            out.append(
                "- warm-up: "
                + (f"{warm} bars at the defaults" if warm is not None else "set by the parameters")
                + "; the first known value is at that index on clean data"
            )
            out.append(
                "- memory: "
                + ("finite: it forgets any bar after its window" if row["memory"] == "finite"
                   else "infinite: the seed fades; see `settle(eps)`")
            )
            legacy = _legacy(row)
            if legacy:
                out.append(f"- legacy: {legacy}")
            if row["talib_name"]:
                out.append(f"- TA-Lib: `{row['talib_name']}`")
            out.append(f"- invariance: {', '.join(row['invariance']) or 'none'}")
            out.append(f"- revision: {row['rev']} (a change to the numbers raises it, and the program hash with it)")
            for ref in row["refs"]:
                out.append(f"- reference: {ref}")
    return "\n".join(out) + "\n"


def generate() -> str:
    from raptorbt import expressions

    rows = [expressions.describe(f["name"]) for f in expressions.functions()]
    return render(rows)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail when the page differs from what the registry generates")
    args = ap.parse_args()
    text = generate()
    if args.check:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run python scripts/gen_expr.py", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
